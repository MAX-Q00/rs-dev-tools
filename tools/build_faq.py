#!/usr/bin/env python3
"""Generate rs-dev-tools/faq_data.lua from release/faq/discord-dev-faq.md.
Each "### N. title" is one question. Each "- **Post:** ROLE | user | tag | date"
starts one post of the conversation; its indented "  - " lines are separate
lines of that post. Text in backticks also goes to the entry's code list."""
import re, sys, pathlib
here = pathlib.Path(__file__).resolve().parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "faq" / "discord-dev-faq.md"
out = here.parent / "rs-dev-tools" / "faq_data.lua"
def clean(s):
    s = re.sub(r"\*\*|`", "", s)
    s = s.replace("<", "").replace(">", "")
    s = s.replace("\u2013", "-").replace("\u2014", "-").replace("\u2019", "'").replace("\u201c", '"').replace("\u201d", '"')
    s = s.encode("ascii", "ignore").decode()
    return re.sub(r"\s+", " ", s).strip()
def cleancode(s):   # keep <pluginname> placeholders readable inside code
    return clean(s.replace("<", "[").replace(">", "]"))
items, section = [], ""
for block in re.split(r"\n(?=## |### )", src.read_text(encoding="utf-8")):
    if block.startswith("## "):
        section = clean(block.splitlines()[0][3:]); continue
    m = re.match(r"### (\d+)\. (.+)", block)
    if not m: continue
    e = dict(n=int(m.group(1)), q=clean(m.group(2)), freq="", where="", section=section, posts=[], code=[])
    for line in block.splitlines()[1:]:
        st = line.strip()
        if st.startswith("- **Frequency:**"): e["freq"] = clean(st[16:]); continue
        if st.startswith("- **Where / when:**"): e["where"] = clean(st[19:]); continue
        pm = re.match(r"- \*\*Post:\*\* (.*)", st)
        if pm:
            f = [x.strip() for x in pm.group(1).split("|")] + ["", "", "", ""]
            e["posts"].append(dict(role=f[0].upper() or "A", user=clean(f[1]) or "Unknown user", tag=clean(f[2]), date=clean(f[3]), lines=[]))
            continue
        if st.startswith("- ") and e["posts"] and line.startswith("  "):
            raw = st[2:]
            for span in re.findall(r"`([^`]+)`", raw):
                c = cleancode(span)
                if c and c not in e["code"]: e["code"].append(c)
            txt = re.sub(r"`([^`]+)`", lambda mm: cleancode(mm.group(1)), raw)
            e["posts"][-1]["lines"].append(clean(re.sub(r"\*\*|", "", txt)))
    if not e["posts"]: continue
    ans = [p for p in e["posts"] if p["role"] == "A"]
    e["a"] = " ".join(" ".join(p["lines"]) for p in ans)
    e["main"] = ans[0] if ans else None
    items.append(e)
def lq(s): return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'
L = ["-- Generated by release/build_faq.py from release/faq/discord-dev-faq.md.", "-- Do not edit by hand.", "return {"]
for e in items:
    posts = []
    for p in e["posts"]:
        posts.append("{ role = %s, user = %s, tag = %s, date = %s, lines = { %s } }" % (lq(p["role"]), lq(p["user"]), lq(p["tag"]), lq(p["date"]), ", ".join(lq(x) for x in p["lines"])))
    L.append("    { n = %d, q = %s, a = %s, freq = %s, section = %s, where = %s, code = { %s },\n      posts = {\n        %s } }," % (
        e["n"], lq(e["q"]), lq(e["a"]), lq(e["freq"]), lq(e["section"]), lq(e["where"]), ", ".join(lq(c) for c in e["code"]), ",\n        ".join(posts)))
L.append("}")
out.write_text("\n".join(L) + "\n", encoding="ascii")
allp = [p for e in items for p in e["posts"]]
named = sum(1 for e in items if all(p["user"] != "Unknown user" for p in e["posts"]))
none_ = sum(1 for e in items if all(p["user"] == "Unknown user" for p in e["posts"]))
print(f"{len(items)} entries, {len(allp)} posts ({sum(p['user']=='Unknown user' for p in allp)} Unknown user) -> {out}")
print(f"entries: all posters named {named}, mixed {len(items)-named-none_}, all Unknown {none_}")
